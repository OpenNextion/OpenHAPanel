function getSensorRangeIcon(state: string | undefined, ranges: readonly [number, string][], fallback: string) {
    if (state === undefined || !state.trim()) return fallback;
    const value = Number(state);
    if (!Number.isFinite(value)) return fallback;
    return ranges.reduce((icon, [threshold, candidate]) => value >= threshold ? candidate : icon, fallback);
}

